SET CURRENT SQLID = 'BILADM';

-- DCLGEN BILDACT PREFIX ACT
CREATE TABLE BILDB.BIL_ACCOUNT
  (ACCOUNT_ID         INTEGER        NOT NULL,
   ACCOUNT_NUMBER     CHAR(10)       NOT NULL,
   GENAPP_CUST_NUM    INTEGER        NOT NULL WITH DEFAULT 0,
   ACCOUNT_NAME       VARCHAR(60)    NOT NULL,
   ACCOUNT_TYPE       CHAR(4)        NOT NULL,
   BILLING_LEVEL      CHAR(4)        NOT NULL WITH DEFAULT 'ACCT',
   INVOICE_DAY        SMALLINT       NOT NULL WITH DEFAULT 1,
   DELIVERY_METHOD    CHAR(4)        NOT NULL WITH DEFAULT 'MAIL',
   DELINQ_PLAN_CODE   CHAR(8)        NOT NULL,
   AUTOPAY_FLAG       CHAR(1)        NOT NULL WITH DEFAULT 'N',
   AUTOPAY_INSTR_ID   INTEGER        NOT NULL WITH DEFAULT 0,
   ACCOUNT_STATUS     CHAR(4)        NOT NULL WITH DEFAULT 'ACTV',
   COLLECTION_STATUS  CHAR(4)        NOT NULL WITH DEFAULT 'NORM',
   UNAPPLIED_AMT      DECIMAL(13,2)  NOT NULL WITH DEFAULT 0,
   BILLED_AMT         DECIMAL(13,2)  NOT NULL WITH DEFAULT 0,
   DUE_AMT            DECIMAL(13,2)  NOT NULL WITH DEFAULT 0,
   UNBILLED_AMT       DECIMAL(13,2)  NOT NULL WITH DEFAULT 0,
   CURRENCY_CODE      CHAR(3)        NOT NULL WITH DEFAULT 'GBP',
   OPEN_DATE          DATE           NOT NULL,
   CLOSE_DATE         DATE,
   CREATE_USER        CHAR(8)        NOT NULL,
   CREATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   UPDATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   VERSION_NO         INTEGER        NOT NULL WITH DEFAULT 1,
   PRIMARY KEY (ACCOUNT_ID))
  IN BILDB.BILTS02;
CREATE UNIQUE INDEX BILDB.XACT01 ON BILDB.BIL_ACCOUNT (ACCOUNT_NUMBER);
CREATE INDEX BILDB.XACT02 ON BILDB.BIL_ACCOUNT (GENAPP_CUST_NUM);

-- DCLGEN BILDACN PREFIX ACN
CREATE TABLE BILDB.BIL_ACCOUNT_CONTACT
  (ACCOUNT_ID         INTEGER        NOT NULL,
   CONTACT_SEQ        SMALLINT       NOT NULL,
   CONTACT_ROLE       CHAR(4)        NOT NULL,
   CONTACT_TYPE       CHAR(1)        NOT NULL,
   FIRST_NAME         VARCHAR(30),
   LAST_NAME          VARCHAR(40),
   COMPANY_NAME       VARCHAR(60),
   ADDRESS_LINE1      VARCHAR(60)    NOT NULL,
   ADDRESS_LINE2      VARCHAR(60),
   CITY               VARCHAR(40),
   POSTCODE           CHAR(8)        NOT NULL,
   COUNTRY_CODE       CHAR(2)        NOT NULL WITH DEFAULT 'GB',
   EMAIL_ADDRESS      VARCHAR(100),
   PHONE_NUMBER       CHAR(20),
   PRIMARY_FLAG       CHAR(1)        NOT NULL WITH DEFAULT 'N',
   UPDATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   PRIMARY KEY (ACCOUNT_ID, CONTACT_SEQ),
   FOREIGN KEY (ACCOUNT_ID) REFERENCES BILDB.BIL_ACCOUNT ON DELETE RESTRICT)
  IN BILDB.BILTS02;

-- DCLGEN BILDPIN PREFIX PIN
CREATE TABLE BILDB.BIL_PAYMENT_INSTRUMENT
  (INSTR_ID           INTEGER        NOT NULL,
   ACCOUNT_ID         INTEGER        NOT NULL,
   INSTR_TYPE         CHAR(4)        NOT NULL,
   TOKEN_REF          CHAR(32)       NOT NULL,
   LAST_FOUR          CHAR(4)        NOT NULL WITH DEFAULT ' ',
   EXPIRY_MMYY        CHAR(4)        NOT NULL WITH DEFAULT ' ',
   SORT_CODE          CHAR(6)        NOT NULL WITH DEFAULT ' ',
   HOLDER_NAME        VARCHAR(60),
   INSTR_STATUS       CHAR(4)        NOT NULL WITH DEFAULT 'ACTV',
   FAIL_COUNT         SMALLINT       NOT NULL WITH DEFAULT 0,
   CREATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   PRIMARY KEY (INSTR_ID),
   FOREIGN KEY (ACCOUNT_ID) REFERENCES BILDB.BIL_ACCOUNT ON DELETE RESTRICT)
  IN BILDB.BILTS02;

-- DCLGEN BILDHLD PREFIX HLD
CREATE TABLE BILDB.BIL_HOLD
  (HOLD_ID            INTEGER        NOT NULL,
   ACCOUNT_ID         INTEGER        NOT NULL,
   HOLD_TYPE          CHAR(4)        NOT NULL,
   START_DATE         DATE           NOT NULL,
   END_DATE           DATE,
   HOLD_REASON        VARCHAR(80)    NOT NULL,
   HOLD_STATUS        CHAR(4)        NOT NULL WITH DEFAULT 'ACTV',
   CREATE_USER        CHAR(8)        NOT NULL,
   CREATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   PRIMARY KEY (HOLD_ID),
   FOREIGN KEY (ACCOUNT_ID) REFERENCES BILDB.BIL_ACCOUNT ON DELETE RESTRICT)
  IN BILDB.BILTS02;

-- DCLGEN BILDIST PREFIX IST
CREATE TABLE BILDB.BIL_INVOICE_STREAM
  (STREAM_ID          INTEGER        NOT NULL,
   ACCOUNT_ID         INTEGER        NOT NULL,
   PERIODICITY        CHAR(1)        NOT NULL,
   ANCHOR_DAY         SMALLINT       NOT NULL,
   STREAM_STATUS      CHAR(4)        NOT NULL WITH DEFAULT 'ACTV',
   PRIMARY KEY (STREAM_ID),
   FOREIGN KEY (ACCOUNT_ID) REFERENCES BILDB.BIL_ACCOUNT ON DELETE RESTRICT)
  IN BILDB.BILTS02;
