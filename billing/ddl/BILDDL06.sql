SET CURRENT SQLID = 'BILADM';

-- DCLGEN BILDDLP PREFIX DLP
CREATE TABLE BILDB.BIL_DELINQ_PROCESS
  (DP_ID              INTEGER        NOT NULL,
   ACCOUNT_ID         INTEGER        NOT NULL,
   PP_ID              INTEGER        NOT NULL,
   PLAN_CODE          CHAR(8)        NOT NULL,
   START_DATE         DATE           NOT NULL,
   PASTDUE_AMOUNT     DECIMAL(13,2)  NOT NULL,
   CURRENT_STEP       SMALLINT       NOT NULL WITH DEFAULT 0,
   DP_STATUS          CHAR(4)        NOT NULL WITH DEFAULT 'OPEN',
   EXIT_REASON        CHAR(8)        NOT NULL WITH DEFAULT ' ',
   EXIT_DATE          DATE,
   UPDATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   PRIMARY KEY (DP_ID))
  IN BILDB.BILTS06;
CREATE INDEX BILDB.XDLP01 ON BILDB.BIL_DELINQ_PROCESS (ACCOUNT_ID, DP_STATUS);

-- DCLGEN BILDDEV PREFIX DEV
CREATE TABLE BILDB.BIL_DELINQ_EVENT
  (DP_ID              INTEGER        NOT NULL,
   STEP_SEQ           SMALLINT       NOT NULL,
   EVENT_CODE         CHAR(8)        NOT NULL,
   TARGET_DATE        DATE           NOT NULL,
   COMPLETED_DATE     DATE,
   EVENT_STATUS       CHAR(4)        NOT NULL WITH DEFAULT 'PEND',
   RESULT_REF         CHAR(20)       NOT NULL WITH DEFAULT ' ',
   PRIMARY KEY (DP_ID, STEP_SEQ),
   FOREIGN KEY (DP_ID) REFERENCES BILDB.BIL_DELINQ_PROCESS ON DELETE CASCADE)
  IN BILDB.BILTS06;

-- DCLGEN BILDWOF PREFIX WOF
CREATE TABLE BILDB.BIL_WRITEOFF
  (WO_ID              INTEGER        NOT NULL,
   ACCOUNT_ID         INTEGER        NOT NULL,
   ITEM_ID            INTEGER        NOT NULL,
   WO_AMOUNT          DECIMAL(13,2)  NOT NULL,
   WO_REASON          CHAR(8)        NOT NULL,
   WO_STATUS          CHAR(4)        NOT NULL WITH DEFAULT 'APPR',
   REQUEST_USER       CHAR(8)        NOT NULL,
   APPROVER_USER      CHAR(8)        NOT NULL WITH DEFAULT ' ',
   WO_DATE            DATE           NOT NULL,
   REVERSED_FLAG      CHAR(1)        NOT NULL WITH DEFAULT 'N',
   CREATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   PRIMARY KEY (WO_ID))
  IN BILDB.BILTS06;

-- DCLGEN BILDDSB PREFIX DSB
CREATE TABLE BILDB.BIL_DISBURSEMENT
  (DISB_ID            INTEGER        NOT NULL,
   ACCOUNT_ID         INTEGER        NOT NULL WITH DEFAULT 0,
   DISB_AMOUNT        DECIMAL(13,2)  NOT NULL,
   DISB_REASON        CHAR(8)        NOT NULL,
   PAYEE_NAME         VARCHAR(60)    NOT NULL,
   PAYEE_ADDR1        VARCHAR(60),
   PAYEE_POSTCODE     CHAR(8),
   PAY_METHOD         CHAR(4)        NOT NULL WITH DEFAULT 'CHEQ',
   INSTR_ID           INTEGER        NOT NULL WITH DEFAULT 0,
   DUE_DATE           DATE           NOT NULL,
   DISB_STATUS        CHAR(4)        NOT NULL WITH DEFAULT 'PEND',
   SOURCE_SYSTEM      CHAR(4)        NOT NULL WITH DEFAULT 'BILL',
   SOURCE_REF         CHAR(20)       NOT NULL WITH DEFAULT ' ',
   REQUEST_USER       CHAR(8)        NOT NULL,
   APPROVER_USER      CHAR(8)        NOT NULL WITH DEFAULT ' ',
   SENT_DATE          DATE,
   VOID_REASON        CHAR(8)        NOT NULL WITH DEFAULT ' ',
   CREATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   UPDATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   PRIMARY KEY (DISB_ID))
  IN BILDB.BILTS06;
CREATE INDEX BILDB.XDSB01 ON BILDB.BIL_DISBURSEMENT (DISB_STATUS, DUE_DATE);
