SET CURRENT SQLID = 'BILADM';

-- DCLGEN BILDTXN PREFIX TXN
CREATE TABLE BILDB.BIL_TRANSACTION
  (TXN_ID             INTEGER        NOT NULL,
   ACCOUNT_ID         INTEGER        NOT NULL WITH DEFAULT 0,
   PRODUCER_ID        INTEGER        NOT NULL WITH DEFAULT 0,
   TXN_TYPE           CHAR(8)        NOT NULL,
   TXN_AMOUNT         DECIMAL(13,2)  NOT NULL,
   REF_TYPE           CHAR(4)        NOT NULL,
   REF_ID             INTEGER        NOT NULL,
   BUSINESS_DATE      DATE           NOT NULL,
   REVERSAL_OF_TXN    INTEGER        NOT NULL WITH DEFAULT 0,
   CREATE_USER        CHAR(8)        NOT NULL,
   CREATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   PRIMARY KEY (TXN_ID))
  IN BILDB.BILTS08;
CREATE INDEX BILDB.XTXN01 ON BILDB.BIL_TRANSACTION (ACCOUNT_ID, BUSINESS_DATE);

-- DCLGEN BILDLGL PREFIX LGL
CREATE TABLE BILDB.BIL_LEDGER_LINE
  (TXN_ID             INTEGER        NOT NULL,
   LINE_SEQ           SMALLINT       NOT NULL,
   T_ACCOUNT          CHAR(8)        NOT NULL,
   DR_CR              CHAR(1)        NOT NULL,
   LINE_AMOUNT        DECIMAL(13,2)  NOT NULL,
   ACCOUNT_ID         INTEGER        NOT NULL WITH DEFAULT 0,
   BUSINESS_DATE      DATE           NOT NULL,
   PRIMARY KEY (TXN_ID, LINE_SEQ),
   FOREIGN KEY (TXN_ID) REFERENCES BILDB.BIL_TRANSACTION ON DELETE RESTRICT)
  IN BILDB.BILTS08;
CREATE INDEX BILDB.XLGL01 ON BILDB.BIL_LEDGER_LINE (T_ACCOUNT, BUSINESS_DATE);

-- DCLGEN BILDAUD PREFIX AUD
CREATE TABLE BILDB.BIL_AUDIT
  (AUDIT_ID           INTEGER        NOT NULL,
   ENTITY_NAME        CHAR(8)        NOT NULL,
   ENTITY_KEY         CHAR(20)       NOT NULL,
   ACTION_CODE        CHAR(4)        NOT NULL,
   FIELD_NAME         CHAR(18)       NOT NULL WITH DEFAULT ' ',
   BEFORE_VALUE       VARCHAR(100),
   AFTER_VALUE        VARCHAR(100),
   USER_ID            CHAR(8)        NOT NULL,
   PROGRAM_ID         CHAR(8)        NOT NULL,
   AUDIT_TS           TIMESTAMP      NOT NULL WITH DEFAULT,
   PRIMARY KEY (AUDIT_ID))
  IN BILDB.BILTS08;

-- DCLGEN BILDEVQ PREFIX EVQ
CREATE TABLE BILDB.BIL_EVENT_QUEUE
  (EVENT_ID           INTEGER        NOT NULL,
   EVENT_TYPE         CHAR(8)        NOT NULL,
   DIRECTION          CHAR(1)        NOT NULL,
   SOURCE_SYSTEM      CHAR(4)        NOT NULL,
   TARGET_SYSTEM      CHAR(4)        NOT NULL,
   EVENT_KEY          CHAR(20)       NOT NULL,
   PAYLOAD            VARCHAR(1000)  NOT NULL,
   EVENT_STATUS       CHAR(4)        NOT NULL WITH DEFAULT 'NEW',
   RETRY_COUNT        SMALLINT       NOT NULL WITH DEFAULT 0,
   ERROR_TEXT         VARCHAR(80),
   CREATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   PROCESSED_TS       TIMESTAMP,
   PRIMARY KEY (EVENT_ID))
  IN BILDB.BILTS08;
CREATE INDEX BILDB.XEVQ01 ON BILDB.BIL_EVENT_QUEUE (EVENT_STATUS, DIRECTION, CREATE_TS);

-- DCLGEN BILDTTK PREFIX TTK
CREATE TABLE BILDB.BIL_TROUBLE_TICKET
  (TICKET_ID          INTEGER        NOT NULL,
   ACCOUNT_ID         INTEGER        NOT NULL,
   TICKET_TYPE        CHAR(8)        NOT NULL,
   PRIORITY           CHAR(1)        NOT NULL WITH DEFAULT '3',
   SUBJECT            VARCHAR(80)    NOT NULL,
   TICKET_STATUS      CHAR(4)        NOT NULL WITH DEFAULT 'OPEN',
   ASSIGNED_USER      CHAR(8)        NOT NULL WITH DEFAULT ' ',
   HOLD_ID            INTEGER        NOT NULL WITH DEFAULT 0,
   DUE_DATE           DATE           NOT NULL,
   CREATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   CLOSE_TS           TIMESTAMP,
   PRIMARY KEY (TICKET_ID))
  IN BILDB.BILTS08;
