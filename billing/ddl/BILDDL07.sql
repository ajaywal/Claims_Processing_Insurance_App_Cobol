SET CURRENT SQLID = 'BILADM';

-- DCLGEN BILDPRD PREFIX PRD
CREATE TABLE BILDB.BIL_PRODUCER
  (PRODUCER_ID        INTEGER        NOT NULL,
   PRODUCER_CODE      INTEGER        NOT NULL,
   PRODUCER_NAME      VARCHAR(60)    NOT NULL,
   PRODUCER_TIER      CHAR(4)        NOT NULL WITH DEFAULT 'STD',
   COMM_PLAN_CODE     CHAR(8)        NOT NULL,
   PAY_CYCLE          CHAR(1)        NOT NULL WITH DEFAULT 'M',
   AGENCY_BILL_FLAG   CHAR(1)        NOT NULL WITH DEFAULT 'N',
   PAYABLE_BALANCE    DECIMAL(13,2)  NOT NULL WITH DEFAULT 0,
   PRODUCER_STATUS    CHAR(4)        NOT NULL WITH DEFAULT 'ACTV',
   UPDATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   PRIMARY KEY (PRODUCER_ID))
  IN BILDB.BILTS07;
CREATE UNIQUE INDEX BILDB.XPRD01 ON BILDB.BIL_PRODUCER (PRODUCER_CODE);

-- DCLGEN BILDCMI PREFIX CMI
CREATE TABLE BILDB.BIL_COMMISSION_ITEM
  (CI_ID              INTEGER        NOT NULL,
   PRODUCER_ID        INTEGER        NOT NULL,
   ITEM_ID            INTEGER        NOT NULL,
   PP_ID              INTEGER        NOT NULL,
   BASIS_AMOUNT       DECIMAL(13,2)  NOT NULL,
   RATE_BPS           SMALLINT       NOT NULL,
   COMM_AMOUNT        DECIMAL(13,2)  NOT NULL,
   EARNED_AMOUNT      DECIMAL(13,2)  NOT NULL WITH DEFAULT 0,
   CI_STATE           CHAR(4)        NOT NULL WITH DEFAULT 'RSRV',
   PRODUCER_PAY_ID    INTEGER        NOT NULL WITH DEFAULT 0,
   UPDATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   PRIMARY KEY (CI_ID))
  IN BILDB.BILTS07;
CREATE INDEX BILDB.XCMI01 ON BILDB.BIL_COMMISSION_ITEM (PRODUCER_ID, CI_STATE);
CREATE INDEX BILDB.XCMI02 ON BILDB.BIL_COMMISSION_ITEM (ITEM_ID);

-- DCLGEN BILDPPY PREFIX PPY
CREATE TABLE BILDB.BIL_PRODUCER_PAYMENT
  (PRODUCER_PAY_ID    INTEGER        NOT NULL,
   PRODUCER_ID        INTEGER        NOT NULL,
   PERIOD_END         DATE           NOT NULL,
   PAY_AMOUNT         DECIMAL(13,2)  NOT NULL,
   ITEM_COUNT         INTEGER        NOT NULL,
   PAY_STATUS         CHAR(4)        NOT NULL WITH DEFAULT 'PEND',
   DISB_ID            INTEGER        NOT NULL WITH DEFAULT 0,
   CREATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   PRIMARY KEY (PRODUCER_PAY_ID))
  IN BILDB.BILTS07;

-- DCLGEN BILDAGS PREFIX AGS
CREATE TABLE BILDB.BIL_AGENCY_STATEMENT
  (STMT_ID            INTEGER        NOT NULL,
   PRODUCER_ID        INTEGER        NOT NULL,
   STMT_DATE          DATE           NOT NULL,
   DUE_DATE           DATE           NOT NULL,
   GROSS_AMOUNT       DECIMAL(13,2)  NOT NULL,
   COMMISSION_AMOUNT  DECIMAL(13,2)  NOT NULL,
   NET_DUE            DECIMAL(13,2)  NOT NULL,
   PAID_AMOUNT        DECIMAL(13,2)  NOT NULL WITH DEFAULT 0,
   STMT_STATUS        CHAR(4)        NOT NULL WITH DEFAULT 'OPEN',
   ITEM_COUNT         INTEGER        NOT NULL,
   CREATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   PRIMARY KEY (STMT_ID))
  IN BILDB.BILTS07;
