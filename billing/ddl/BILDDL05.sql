SET CURRENT SQLID = 'BILADM';

-- DCLGEN BILDRCP PREFIX RCP
CREATE TABLE BILDB.BIL_PAYMENT_RECEIPT
  (MONEY_ID           INTEGER        NOT NULL,
   ACCOUNT_ID         INTEGER        NOT NULL WITH DEFAULT 0,
   RECEIVED_DATE      DATE           NOT NULL,
   RECEIPT_AMOUNT     DECIMAL(13,2)  NOT NULL,
   UNAPPLIED_AMOUNT   DECIMAL(13,2)  NOT NULL WITH DEFAULT 0,
   INSTR_ID           INTEGER        NOT NULL WITH DEFAULT 0,
   PAYMENT_METHOD     CHAR(4)        NOT NULL,
   REF_NUMBER         CHAR(20)       NOT NULL WITH DEFAULT ' ',
   INVOICE_NUMBER     CHAR(12)       NOT NULL WITH DEFAULT ' ',
   RECEIPT_SOURCE     CHAR(4)        NOT NULL,
   RECEIPT_STATUS     CHAR(4)        NOT NULL WITH DEFAULT 'RCVD',
   REVERSAL_REASON    CHAR(8)        NOT NULL WITH DEFAULT ' ',
   BATCH_REF          CHAR(12)       NOT NULL WITH DEFAULT ' ',
   CREATE_USER        CHAR(8)        NOT NULL,
   CREATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   UPDATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   PRIMARY KEY (MONEY_ID))
  IN BILDB.BILTS05;
CREATE INDEX BILDB.XRCP01 ON BILDB.BIL_PAYMENT_RECEIPT (ACCOUNT_ID, RECEIVED_DATE);

-- DCLGEN BILDDIS PREFIX DIS
CREATE TABLE BILDB.BIL_DISTRIBUTION
  (DIST_ID            INTEGER        NOT NULL,
   MONEY_ID           INTEGER        NOT NULL,
   ITEM_ID            INTEGER        NOT NULL,
   ACCOUNT_ID         INTEGER        NOT NULL,
   DIST_AMOUNT        DECIMAL(13,2)  NOT NULL,
   DIST_DATE          DATE           NOT NULL,
   REVERSED_FLAG      CHAR(1)        NOT NULL WITH DEFAULT 'N',
   REVERSED_DIST_ID   INTEGER        NOT NULL WITH DEFAULT 0,
   CREATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   PRIMARY KEY (DIST_ID),
   FOREIGN KEY (MONEY_ID) REFERENCES BILDB.BIL_PAYMENT_RECEIPT ON DELETE RESTRICT)
  IN BILDB.BILTS05;
CREATE INDEX BILDB.XDIS01 ON BILDB.BIL_DISTRIBUTION (MONEY_ID);
CREATE INDEX BILDB.XDIS02 ON BILDB.BIL_DISTRIBUTION (ITEM_ID);

-- DCLGEN BILDSUS PREFIX SUS
CREATE TABLE BILDB.BIL_SUSPENSE
  (SUSP_ID            INTEGER        NOT NULL,
   MONEY_ID           INTEGER        NOT NULL,
   SUSP_AMOUNT        DECIMAL(13,2)  NOT NULL,
   REF_TEXT           VARCHAR(80)    NOT NULL,
   SUSP_REASON        CHAR(8)        NOT NULL,
   SUSP_STATUS        CHAR(4)        NOT NULL WITH DEFAULT 'OPEN',
   MATCHED_ACCOUNT_ID INTEGER        NOT NULL WITH DEFAULT 0,
   CREATE_DATE        DATE           NOT NULL,
   RESOLVED_DATE      DATE,
   RESOLVED_USER      CHAR(8)        NOT NULL WITH DEFAULT ' ',
   PRIMARY KEY (SUSP_ID))
  IN BILDB.BILTS05;

-- DCLGEN BILDPRQ PREFIX PRQ
CREATE TABLE BILDB.BIL_PAYMENT_REQUEST
  (REQUEST_ID         INTEGER        NOT NULL,
   ACCOUNT_ID         INTEGER        NOT NULL,
   INSTR_ID           INTEGER        NOT NULL,
   INVOICE_ID         INTEGER        NOT NULL,
   REQUEST_AMOUNT     DECIMAL(13,2)  NOT NULL,
   DRAFT_DATE         DATE           NOT NULL,
   REQUEST_STATUS     CHAR(4)        NOT NULL WITH DEFAULT 'CRTD',
   MONEY_ID           INTEGER        NOT NULL WITH DEFAULT 0,
   RETURN_CODE        CHAR(4)        NOT NULL WITH DEFAULT ' ',
   FILE_REF           CHAR(12)       NOT NULL WITH DEFAULT ' ',
   CREATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   UPDATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   PRIMARY KEY (REQUEST_ID))
  IN BILDB.BILTS05;
CREATE INDEX BILDB.XPRQ01 ON BILDB.BIL_PAYMENT_REQUEST (DRAFT_DATE, REQUEST_STATUS);
