--********************************************************************
-- BillingCoreAJ2026  BILDDL01  Reference & control tables
-- Synthetic BillingCenter-parity billing system. Db2 for z/OS.
-- Convention: "-- DCLGEN <member> PREFIX <pfx>" precedes each table
-- and drives tools/dclgen.py, which writes cpy/<member>.cpy.
--********************************************************************
SET CURRENT SQLID = 'BILADM';

-- DCLGEN BILDCTL PREFIX CTL
CREATE TABLE BILDB.BIL_CONTROL
  (CONTROL_KEY        CHAR(8)        NOT NULL,
   BUSINESS_DATE      DATE           NOT NULL,
   PRIOR_BUS_DATE     DATE           NOT NULL,
   BATCH_STATUS       CHAR(1)        NOT NULL WITH DEFAULT 'O',
   LAST_EOD_TS        TIMESTAMP,
   CURRENCY_CODE      CHAR(3)        NOT NULL WITH DEFAULT 'GBP',
   UPDATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   PRIMARY KEY (CONTROL_KEY))
  IN BILDB.BILTS01;

-- DCLGEN BILDSEQ PREFIX SEQ
CREATE TABLE BILDB.BIL_SEQUENCE
  (SEQ_NAME           CHAR(8)        NOT NULL,
   NEXT_VALUE         INTEGER        NOT NULL,
   INCREMENT_BY       SMALLINT       NOT NULL WITH DEFAULT 1,
   MAX_VALUE          INTEGER        NOT NULL,
   CYCLE_FLAG         CHAR(1)        NOT NULL WITH DEFAULT 'N',
   PREFIX_TEXT        CHAR(4)        NOT NULL WITH DEFAULT ' ',
   UPDATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   PRIMARY KEY (SEQ_NAME))
  IN BILDB.BILTS01;

-- DCLGEN BILDCOD PREFIX COD
CREATE TABLE BILDB.BIL_CODE_TABLE
  (TABLE_NAME         CHAR(8)        NOT NULL,
   CODE_VALUE         CHAR(10)       NOT NULL,
   DESCRIPTION        VARCHAR(60)    NOT NULL,
   SORT_ORDER         SMALLINT       NOT NULL WITH DEFAULT 0,
   ACTIVE_FLAG        CHAR(1)        NOT NULL WITH DEFAULT 'Y',
   PRIMARY KEY (TABLE_NAME, CODE_VALUE))
  IN BILDB.BILTS01;

-- DCLGEN BILDCAL PREFIX CAL
CREATE TABLE BILDB.BIL_CALENDAR
  (CAL_DATE           DATE           NOT NULL,
   DAY_OF_WEEK        SMALLINT       NOT NULL,
   HOLIDAY_FLAG       CHAR(1)        NOT NULL WITH DEFAULT 'N',
   HOLIDAY_NAME       VARCHAR(40),
   PRIMARY KEY (CAL_DATE))
  IN BILDB.BILTS01;

-- DCLGEN BILDPPL PREFIX PPL
CREATE TABLE BILDB.BIL_PAYMENT_PLAN
  (PLAN_CODE          CHAR(8)        NOT NULL,
   PLAN_NAME          VARCHAR(40)    NOT NULL,
   DOWNPAY_PCT        DECIMAL(5,2)   NOT NULL,
   NUM_INSTALLMENTS   SMALLINT       NOT NULL,
   FREQUENCY          CHAR(1)        NOT NULL,
   INSTALL_FEE        DECIMAL(9,2)   NOT NULL WITH DEFAULT 0,
   DAYS_BILL_BEFORE   SMALLINT       NOT NULL WITH DEFAULT 20,
   FIRST_INST_MONTHS  SMALLINT       NOT NULL WITH DEFAULT 1,
   MIN_INST_AMOUNT    DECIMAL(9,2)   NOT NULL WITH DEFAULT 0,
   ACTIVE_FLAG        CHAR(1)        NOT NULL WITH DEFAULT 'Y',
   PRIMARY KEY (PLAN_CODE))
  IN BILDB.BILTS01;

-- DCLGEN BILDDPL PREFIX DPL
CREATE TABLE BILDB.BIL_DELINQ_PLAN
  (PLAN_CODE          CHAR(8)        NOT NULL,
   PLAN_NAME          VARCHAR(40)    NOT NULL,
   GRACE_DAYS         SMALLINT       NOT NULL,
   LATE_FEE           DECIMAL(9,2)   NOT NULL,
   REINSTATE_FEE      DECIMAL(9,2)   NOT NULL,
   PASTDUE_THRESHOLD  DECIMAL(9,2)   NOT NULL,
   WRITEOFF_THRESHOLD DECIMAL(9,2)   NOT NULL,
   ACTIVE_FLAG        CHAR(1)        NOT NULL WITH DEFAULT 'Y',
   PRIMARY KEY (PLAN_CODE))
  IN BILDB.BILTS01;

-- DCLGEN BILDDST PREFIX DST
CREATE TABLE BILDB.BIL_DELINQ_STEP
  (PLAN_CODE          CHAR(8)        NOT NULL,
   STEP_SEQ           SMALLINT       NOT NULL,
   EVENT_CODE         CHAR(8)        NOT NULL,
   DAYS_AFTER_START   SMALLINT       NOT NULL,
   DOC_TYPE           CHAR(8)        NOT NULL WITH DEFAULT ' ',
   PRIMARY KEY (PLAN_CODE, STEP_SEQ))
  IN BILDB.BILTS01;

-- DCLGEN BILDCPL PREFIX CPL
CREATE TABLE BILDB.BIL_COMMISSION_PLAN
  (PLAN_CODE          CHAR(8)        NOT NULL,
   PLAN_NAME          VARCHAR(40)    NOT NULL,
   DEFAULT_RATE_BPS   SMALLINT       NOT NULL,
   EARN_BASIS         CHAR(1)        NOT NULL,
   PAY_THRESHOLD      DECIMAL(9,2)   NOT NULL WITH DEFAULT 0,
   ACTIVE_FLAG        CHAR(1)        NOT NULL WITH DEFAULT 'Y',
   PRIMARY KEY (PLAN_CODE))
  IN BILDB.BILTS01;

-- DCLGEN BILDCRT PREFIX CRT
CREATE TABLE BILDB.BIL_COMMISSION_RATE
  (PLAN_CODE          CHAR(8)        NOT NULL,
   PRODUCT_CODE       CHAR(1)        NOT NULL,
   CHARGE_PATTERN     CHAR(8)        NOT NULL,
   RATE_BPS           SMALLINT       NOT NULL,
   PRIMARY KEY (PLAN_CODE, PRODUCT_CODE, CHARGE_PATTERN))
  IN BILDB.BILTS01;

-- DCLGEN BILDAUL PREFIX AUL
CREATE TABLE BILDB.BIL_AUTHORITY_LIMIT
  (USER_ROLE          CHAR(8)        NOT NULL,
   LIMIT_TYPE         CHAR(8)        NOT NULL,
   LIMIT_AMOUNT       DECIMAL(13,2)  NOT NULL,
   PRIMARY KEY (USER_ROLE, LIMIT_TYPE))
  IN BILDB.BILTS01;

-- DCLGEN BILDUSR PREFIX USR
CREATE TABLE BILDB.BIL_USER
  (USER_ID            CHAR(8)        NOT NULL,
   USER_NAME          VARCHAR(40)    NOT NULL,
   USER_ROLE          CHAR(8)        NOT NULL,
   SUPERVISOR_ID      CHAR(8)        NOT NULL WITH DEFAULT ' ',
   ACTIVE_FLAG        CHAR(1)        NOT NULL WITH DEFAULT 'Y',
   PRIMARY KEY (USER_ID))
  IN BILDB.BILTS01;
