SET CURRENT SQLID = 'BILADM';

-- DCLGEN BILDPPR PREFIX PPR
CREATE TABLE BILDB.BIL_POLICY_PERIOD
  (PP_ID              INTEGER        NOT NULL,
   ACCOUNT_ID         INTEGER        NOT NULL,
   GENAPP_POL_NUM     INTEGER        NOT NULL,
   TERM_NUMBER        SMALLINT       NOT NULL,
   PRODUCT_CODE       CHAR(1)        NOT NULL,
   EFF_DATE           DATE           NOT NULL,
   EXP_DATE           DATE           NOT NULL,
   PAYMENT_PLAN_CODE  CHAR(8)        NOT NULL,
   BILLING_METHOD     CHAR(2)        NOT NULL,
   PRODUCER_ID        INTEGER        NOT NULL WITH DEFAULT 0,
   STREAM_ID          INTEGER        NOT NULL,
   TOTAL_PREMIUM      DECIMAL(13,2)  NOT NULL WITH DEFAULT 0,
   PP_STATUS          CHAR(4)        NOT NULL WITH DEFAULT 'INFC',
   CANCEL_DATE        DATE,
   CANCEL_REASON      CHAR(8),
   CLOSURE_STATUS     CHAR(4)        NOT NULL WITH DEFAULT 'OPEN',
   CREATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   UPDATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   VERSION_NO         INTEGER        NOT NULL WITH DEFAULT 1,
   PRIMARY KEY (PP_ID),
   FOREIGN KEY (ACCOUNT_ID) REFERENCES BILDB.BIL_ACCOUNT ON DELETE RESTRICT)
  IN BILDB.BILTS03;
CREATE UNIQUE INDEX BILDB.XPPR01
  ON BILDB.BIL_POLICY_PERIOD (GENAPP_POL_NUM, TERM_NUMBER);

-- DCLGEN BILDCHG PREFIX CHG
CREATE TABLE BILDB.BIL_CHARGE
  (CHARGE_ID          INTEGER        NOT NULL,
   PP_ID              INTEGER        NOT NULL,
   ACCOUNT_ID         INTEGER        NOT NULL,
   CHARGE_PATTERN     CHAR(8)        NOT NULL,
   BILLING_INSTR      CHAR(8)        NOT NULL,
   CHARGE_AMOUNT      DECIMAL(13,2)  NOT NULL,
   CHARGE_DATE        DATE           NOT NULL,
   EFF_DATE           DATE           NOT NULL,
   CHARGE_STATUS      CHAR(4)        NOT NULL WITH DEFAULT 'OPEN',
   SOURCE_REF         CHAR(20)       NOT NULL WITH DEFAULT ' ',
   CREATE_USER        CHAR(8)        NOT NULL,
   CREATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   PRIMARY KEY (CHARGE_ID),
   FOREIGN KEY (PP_ID) REFERENCES BILDB.BIL_POLICY_PERIOD ON DELETE RESTRICT)
  IN BILDB.BILTS03;
CREATE INDEX BILDB.XCHG01 ON BILDB.BIL_CHARGE (PP_ID);

-- DCLGEN BILDITM PREFIX ITM
CREATE TABLE BILDB.BIL_INVOICE_ITEM
  (ITEM_ID            INTEGER        NOT NULL,
   CHARGE_ID          INTEGER        NOT NULL,
   ACCOUNT_ID         INTEGER        NOT NULL,
   PP_ID              INTEGER        NOT NULL,
   INVOICE_ID         INTEGER        NOT NULL WITH DEFAULT 0,
   STREAM_ID          INTEGER        NOT NULL,
   ITEM_TYPE          CHAR(4)        NOT NULL,
   INSTALL_NUMBER     SMALLINT       NOT NULL WITH DEFAULT 0,
   EVENT_DATE         DATE           NOT NULL,
   DUE_DATE           DATE           NOT NULL,
   ITEM_AMOUNT        DECIMAL(13,2)  NOT NULL,
   PAID_AMOUNT        DECIMAL(13,2)  NOT NULL WITH DEFAULT 0,
   WRITEOFF_AMOUNT    DECIMAL(13,2)  NOT NULL WITH DEFAULT 0,
   COMMISSION_AMOUNT  DECIMAL(13,2)  NOT NULL WITH DEFAULT 0,
   ITEM_STATUS        CHAR(4)        NOT NULL WITH DEFAULT 'PLAN',
   PRIORITY_RANK      SMALLINT       NOT NULL WITH DEFAULT 5,
   UPDATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   PRIMARY KEY (ITEM_ID),
   FOREIGN KEY (CHARGE_ID) REFERENCES BILDB.BIL_CHARGE ON DELETE RESTRICT)
  IN BILDB.BILTS03;
CREATE INDEX BILDB.XITM01 ON BILDB.BIL_INVOICE_ITEM (ACCOUNT_ID, ITEM_STATUS, DUE_DATE);
CREATE INDEX BILDB.XITM02 ON BILDB.BIL_INVOICE_ITEM (INVOICE_ID);
CREATE INDEX BILDB.XITM03 ON BILDB.BIL_INVOICE_ITEM (STREAM_ID, EVENT_DATE);
