SET CURRENT SQLID = 'BILADM';

-- DCLGEN BILDINV PREFIX INV
CREATE TABLE BILDB.BIL_INVOICE
  (INVOICE_ID         INTEGER        NOT NULL,
   INVOICE_NUMBER     CHAR(12)       NOT NULL,
   ACCOUNT_ID         INTEGER        NOT NULL,
   STREAM_ID          INTEGER        NOT NULL,
   BILL_DATE          DATE           NOT NULL,
   DUE_DATE           DATE           NOT NULL,
   INVOICE_AMOUNT     DECIMAL(13,2)  NOT NULL,
   AMOUNT_DUE         DECIMAL(13,2)  NOT NULL,
   PRIOR_BALANCE      DECIMAL(13,2)  NOT NULL WITH DEFAULT 0,
   INVOICE_STATUS     CHAR(4)        NOT NULL WITH DEFAULT 'PLAN',
   ADHOC_FLAG         CHAR(1)        NOT NULL WITH DEFAULT 'N',
   ITEM_COUNT         SMALLINT       NOT NULL WITH DEFAULT 0,
   DOC_ID             INTEGER        NOT NULL WITH DEFAULT 0,
   CREATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   UPDATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   PRIMARY KEY (INVOICE_ID),
   FOREIGN KEY (ACCOUNT_ID) REFERENCES BILDB.BIL_ACCOUNT ON DELETE RESTRICT)
  IN BILDB.BILTS04;
CREATE UNIQUE INDEX BILDB.XINV01 ON BILDB.BIL_INVOICE (INVOICE_NUMBER);
CREATE INDEX BILDB.XINV02 ON BILDB.BIL_INVOICE (ACCOUNT_ID, DUE_DATE);

-- DCLGEN BILDDOC PREFIX DOC
CREATE TABLE BILDB.BIL_DOCUMENT_REQUEST
  (DOC_ID             INTEGER        NOT NULL,
   ACCOUNT_ID         INTEGER        NOT NULL,
   DOC_TYPE           CHAR(8)        NOT NULL,
   REF_TYPE           CHAR(4)        NOT NULL,
   REF_ID             INTEGER        NOT NULL,
   DELIVERY_METHOD    CHAR(4)        NOT NULL,
   DOC_STATUS         CHAR(4)        NOT NULL WITH DEFAULT 'RQST',
   REQUEST_DATE       DATE           NOT NULL,
   SENT_TS            TIMESTAMP,
   PRIMARY KEY (DOC_ID))
  IN BILDB.BILTS04;
