#!/usr/bin/env python3
"""dclgen.py - generate DB2 DCLGEN-style COBOL host structures from the suite DDL.

Each table in a DDL member is preceded by a line
    -- DCLGEN <member> PREFIX <pfx>
and the generator writes <member>.cpy next to the app's copybooks with:
  * an EXEC SQL DECLARE ... TABLE block (as real DCLGEN does)
  * 01 DCL<table> host structure, fields named <PFX>-<COLUMN>
  * 01 IND<table> null-indicator structure for nullable columns
Usage: python3 dclgen.py <ddl-dir> <cpy-dir>
"""
import re, sys, os

TYPE_RE = re.compile(r'^\s*\(?\s*([A-Z0-9_]+)\s+([A-Z]+)(\((\d+)(,(\d+))?\))?(.*?)(,)?\s*$')

def cobol_pic(typ, a, b):
    if typ == 'INTEGER':  return 'PIC S9(9) COMP'
    if typ == 'SMALLINT': return 'PIC S9(4) COMP'
    if typ == 'BIGINT':   return 'PIC S9(18) COMP'
    if typ == 'DECIMAL':
        p, s = int(a), int(b or 0)
        return f'PIC S9({p-s})V9({s}) COMP-3' if s else f'PIC S9({p}) COMP-3'
    if typ == 'CHAR':     return f'PIC X({a or 1})'
    if typ == 'DATE':     return 'PIC X(10)'
    if typ == 'TIME':     return 'PIC X(8)'
    if typ == 'TIMESTAMP':return 'PIC X(26)'
    raise ValueError(typ)

def parse(path):
    tables, cur = [], None
    for line in open(path):
        m = re.match(r'--\s*DCLGEN\s+(\S+)\s+PREFIX\s+(\S+)', line)
        if m:
            cur = {'member': m.group(1), 'prefix': m.group(2), 'cols': []}
            continue
        if cur is None:
            continue
        m = re.match(r'\s*CREATE TABLE\s+(\S+)', line)
        if m:
            cur['table'] = m.group(1)
            continue
        if 'table' in cur and re.match(r'\s*(PRIMARY KEY|FOREIGN KEY)', line):
            tables.append(cur); cur = None; continue
        if 'table' in cur:
            m = TYPE_RE.match(line)
            if m and m.group(2) in ('INTEGER','SMALLINT','BIGINT','DECIMAL','CHAR','VARCHAR','DATE','TIME','TIMESTAMP'):
                rest = m.group(7) or ''
                cur['cols'].append({'name': m.group(1), 'type': m.group(2), 'a': m.group(4),
                                    'b': m.group(6), 'null': 'NOT NULL' not in rest})
    return tables

def gen(t):
    tname = t['table'].split('.')[-1]
    short = tname.replace('_', '-')
    pfx = t['prefix']
    out = [f"      ******************************************************************",
           f"      * DCLGEN TABLE({t['table']})".ljust(72) + "*",
           f"      *        LIBRARY(SUITE.CPY({t['member']}))".ljust(72) + "*",
           f"      *        STRUCTURE(DCL{short[:20]}) PREFIX({pfx}-)".ljust(72) + "*",
           f"      * Generated by tools/dclgen.py from the suite DDL - do not edit".ljust(72) + "*",
           f"      ******************************************************************",
           f"           EXEC SQL DECLARE {t['table']} TABLE"]
    for i, c in enumerate(t['cols']):
        typ = c['type'] + (f"({c['a']}" + (f",{c['b']}" if c['b'] else '') + ")" if c['a'] else '')
        sep = '(' if i == 0 else ','
        out.append(f"           {sep} {c['name']:<20} {typ:<14}{'' if c['null'] else ' NOT NULL'}")
    out.append("           ) END-EXEC.")
    out.append(f"       01  DCL{short[:26]}.")
    nullable = []
    for c in t['cols']:
        fld = f"{pfx}-{c['name'].replace('_','-')}"[:30]
        if c['type'] == 'VARCHAR':
            out.append(f"           10 {fld}.")
            ln = f"{fld[:26]}-LEN"; tx = f"{fld[:25]}-TEXT"
            out.append(f"              49 {ln:<28} PIC S9(4) COMP.")
            out.append(f"              49 {tx:<28} PIC X({c['a']}).")
        else:
            out.append(f"           10 {fld:<30} {cobol_pic(c['type'], c['a'], c['b'])}.")
        if c['null']:
            nullable.append(c)
    if nullable:
        out.append(f"       01  IND{short[:26]}.")
        for c in nullable:
            ind = f"{pfx}-{c['name'].replace('_','-')}"[:26] + "-IND"
            out.append(f"           10 {ind:<30} PIC S9(4) COMP.")
    out.append(f"      * THE NUMBER OF COLUMNS DESCRIBED BY THIS DECLARATION IS {len(t['cols'])}")
    return '\n'.join(out) + '\n'

if __name__ == '__main__':
    ddl_dir, cpy_dir = sys.argv[1], sys.argv[2]
    n = 0
    for f in sorted(os.listdir(ddl_dir)):
        if not f.endswith('.sql'): continue
        for t in parse(os.path.join(ddl_dir, f)):
            open(os.path.join(cpy_dir, t['member'] + '.cpy'), 'w').write(gen(t))
            n += 1
            print(f"{t['member']:<9} {t['table']:<32} {len(t['cols']):>3} cols")
    print(f'{n} DCLGEN members written to {cpy_dir}')
