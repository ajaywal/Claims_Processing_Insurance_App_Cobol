#!/usr/bin/env python3
"""bmsgen.py - generate the COBOL symbolic map copybook for a BMS mapset,
as the BMS assembly with TYPE=DSECT, LANG=COBOL would.

Supported: DFHMSD (MODE=INOUT, TIOAPFX=YES), DFHMDI, DFHMDF with a label,
LENGTH=, OCCURS=, PICIN=/PICOUT=. Continuation lines ('X' or '*' in column 72
or a trailing comma) are joined. For every named field the map gets
  <fld>L  PIC S9(4) COMP   length
  <fld>F  PIC X            flag   (REDEFINED by <fld>A attribute)
  <fld>I  PIC X(n)         input
and the output map REDEFINES the input map with <fld>O PIC X(n).
Usage: python3 bmsgen.py <mapset.bms> <out-dir>   -> <out-dir>/<MAPSET>.cpy
"""
import re, sys, os

def statements(path):
    cur = ''
    for raw in open(path):
        line = raw.rstrip('\n')
        if line.startswith('*') or not line.strip():
            continue
        cont = len(line) >= 72 and line[71] not in ' '
        body = line[:71].rstrip()
        if cur:
            cur += body.strip()
        else:
            cur = body
        if not cont and not body.endswith(','):
            yield cur; cur = ''
    if cur: yield cur

def parse_ops(s):
    m = re.match(r'^(\S*)\s+(DFHMSD|DFHMDI|DFHMDF)\s*(.*)$', s)
    if not m: return None
    label, macro, ops = m.groups()
    d, depth, tok = {}, 0, ''
    parts = []
    for ch in ops + ',':
        if ch == "'" : depth ^= 2
        if ch == '(' and not depth & 2: depth += 1
        if ch == ')' and not depth & 2: depth -= 1
        if ch == ',' and depth == 0:
            parts.append(tok); tok = ''
        else: tok += ch
    for p in parts:
        if '=' in p:
            k, v = p.split('=', 1); d[k.strip()] = v.strip()
    return label, macro, d

def gen(path):
    mapset, maps, cur = None, [], None
    for s in statements(path):
        r = parse_ops(s)
        if not r: continue
        label, macro, d = r
        if macro == 'DFHMSD' and d.get('TYPE', '') not in ('FINAL',):
            mapset = mapset or label
        elif macro == 'DFHMDI':
            cur = {'name': label, 'fields': []}; maps.append(cur)
        elif macro == 'DFHMDF' and label and cur is not None:
            ln = int(d.get('LENGTH', '1'))
            cur['fields'].append((label, ln, int(d.get('OCCURS', '1'))))
    out = [f"      * Symbolic map for mapset {mapset} - generated by tools/bmsgen.py",
           f"      * from {os.path.basename(path)}. Do not edit; re-run bmsgen."]
    for m in maps:
        n = m['name']
        out.append(f"       01  {n}I.")
        out.append(f"           02 FILLER                  PIC X(12).")
        for f, ln, oc in m['fields']:
            occ = f" OCCURS {oc} TIMES" if oc > 1 else ''
            if oc > 1:
                out.append(f"           02 {f}D{occ}.")
                lv = '03'
            else:
                lv = '02'
            out.append(f"           {lv} {f+'L':<24} PIC S9(4) COMP.")
            out.append(f"           {lv} {f+'F':<24} PIC X.")
            out.append(f"           {lv} FILLER REDEFINES {f}F.")
            out.append(f"              {'04' if oc>1 else '03'} {f+'A':<21} PIC X.")
            out.append(f"           {lv} {f+'I':<24} PIC X({ln}).")
        out.append(f"       01  {n}O REDEFINES {n}I.")
        out.append(f"           02 FILLER                  PIC X(12).")
        for f, ln, oc in m['fields']:
            if oc > 1:
                out.append(f"           02 {f}E OCCURS {oc} TIMES.")
                out.append(f"              03 FILLER               PIC X(3).")
                out.append(f"              03 {f+'O':<21} PIC X({ln}).")
            else:
                out.append(f"           02 FILLER                  PIC X(3).")
                out.append(f"           02 {f+'O':<24} PIC X({ln}).")
    return mapset, '\n'.join(out) + '\n'

if __name__ == '__main__':
    ms, text = gen(sys.argv[1])
    dst = os.path.join(sys.argv[2], ms + '.cpy')
    open(dst, 'w').write(text)
    print(f'{ms}: {text.count(" 01 ")} records -> {dst}')
