SET CURRENT SQLID = 'CLMADM';

-- DCLGEN CLMDCLM PREFIX CLM
CREATE TABLE CLMDB.CLM_CLAIM
  (CLAIM_ID           INTEGER        NOT NULL,
   CLAIM_NUMBER       CHAR(12)       NOT NULL,
   GENAPP_POL_NUM     INTEGER        NOT NULL,
   GENAPP_CUST_NUM    INTEGER        NOT NULL,
   POLICY_TYPE        CHAR(1)        NOT NULL,
   LOSS_TYPE          CHAR(4)        NOT NULL,
   LOSS_DATE          DATE           NOT NULL,
   LOSS_TIME          TIME,
   REPORTED_DATE      DATE           NOT NULL,
   HOW_REPORTED       CHAR(4)        NOT NULL WITH DEFAULT 'PHON',
   LOSS_CAUSE         CHAR(10)       NOT NULL,
   LOSS_DESC          VARCHAR(250)   NOT NULL,
   LOSS_ADDR_LINE1    VARCHAR(60),
   LOSS_POSTCODE      CHAR(8),
   CLAIM_STATE        CHAR(4)        NOT NULL WITH DEFAULT 'DRFT',
   CLOSE_REASON       CHAR(8)        NOT NULL WITH DEFAULT ' ',
   SEGMENT_CODE       CHAR(8)        NOT NULL WITH DEFAULT ' ',
   SEVERITY           SMALLINT       NOT NULL WITH DEFAULT 1,
   FAULT_RATING       CHAR(4)        NOT NULL WITH DEFAULT 'UNKN',
   COVERAGE_IN_QSTN   CHAR(1)        NOT NULL WITH DEFAULT 'N',
   SIU_SCORE          SMALLINT       NOT NULL WITH DEFAULT 0,
   SIU_STATUS         CHAR(4)        NOT NULL WITH DEFAULT 'NONE',
   LITIGATION_FLAG    CHAR(1)        NOT NULL WITH DEFAULT 'N',
   CAT_CODE           CHAR(8)        NOT NULL WITH DEFAULT ' ',
   TOTAL_LOSS_FLAG    CHAR(1)        NOT NULL WITH DEFAULT 'N',
   DUP_SUSPECT_FLAG   CHAR(1)        NOT NULL WITH DEFAULT 'N',
   ASSIGNED_USER      CHAR(8)        NOT NULL WITH DEFAULT ' ',
   ASSIGNED_GROUP     CHAR(8)        NOT NULL WITH DEFAULT ' ',
   TOTAL_RESERVES     DECIMAL(13,2)  NOT NULL WITH DEFAULT 0,
   TOTAL_PAID         DECIMAL(13,2)  NOT NULL WITH DEFAULT 0,
   TOTAL_RECOVERED    DECIMAL(13,2)  NOT NULL WITH DEFAULT 0,
   TOTAL_INCURRED     DECIMAL(13,2)  NOT NULL WITH DEFAULT 0,
   OPEN_DATE          DATE,
   CLOSE_DATE         DATE,
   REOPEN_COUNT       SMALLINT       NOT NULL WITH DEFAULT 0,
   CREATE_USER        CHAR(8)        NOT NULL,
   CREATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   UPDATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   VERSION_NO         INTEGER        NOT NULL WITH DEFAULT 1,
   PRIMARY KEY (CLAIM_ID))
  IN CLMDB.CLMTS02;
CREATE UNIQUE INDEX CLMDB.XCLM01 ON CLMDB.CLM_CLAIM (CLAIM_NUMBER);
CREATE INDEX CLMDB.XCLM02 ON CLMDB.CLM_CLAIM (GENAPP_POL_NUM, LOSS_DATE);
CREATE INDEX CLMDB.XCLM03 ON CLMDB.CLM_CLAIM (ASSIGNED_USER, CLAIM_STATE);

-- DCLGEN CLMDPSN PREFIX PSN
CREATE TABLE CLMDB.CLM_POLICY_SNAPSHOT
  (CLAIM_ID           INTEGER        NOT NULL,
   POLICY_NUMBER      INTEGER        NOT NULL,
   POLICY_TYPE        CHAR(1)        NOT NULL,
   EFF_DATE           DATE           NOT NULL,
   EXP_DATE           DATE           NOT NULL,
   VERIFIED_FLAG      CHAR(1)        NOT NULL,
   INSURED_NAME       VARCHAR(60)    NOT NULL,
   PRODUCER_CODE      INTEGER        NOT NULL WITH DEFAULT 0,
   STATUS_AT_LOSS     CHAR(4)        NOT NULL,
   BILLING_STATUS     CHAR(4)        NOT NULL WITH DEFAULT ' ',
   SNAPSHOT_TS        TIMESTAMP      NOT NULL WITH DEFAULT,
   PRIMARY KEY (CLAIM_ID),
   FOREIGN KEY (CLAIM_ID) REFERENCES CLMDB.CLM_CLAIM ON DELETE CASCADE)
  IN CLMDB.CLMTS02;

-- DCLGEN CLMDPCV PREFIX PCV
CREATE TABLE CLMDB.CLM_POLICY_COVERAGE
  (CLAIM_ID           INTEGER        NOT NULL,
   COV_SEQ            SMALLINT       NOT NULL,
   COVERAGE_TYPE      CHAR(8)        NOT NULL,
   RISK_UNIT_SEQ      SMALLINT       NOT NULL WITH DEFAULT 1,
   LIMIT_AMOUNT       DECIMAL(13,2)  NOT NULL,
   DEDUCTIBLE_AMOUNT  DECIMAL(13,2)  NOT NULL WITH DEFAULT 0,
   PRIMARY KEY (CLAIM_ID, COV_SEQ),
   FOREIGN KEY (CLAIM_ID) REFERENCES CLMDB.CLM_CLAIM ON DELETE CASCADE)
  IN CLMDB.CLMTS02;

-- DCLGEN CLMDRSK PREFIX RSK
CREATE TABLE CLMDB.CLM_RISK_UNIT
  (CLAIM_ID           INTEGER        NOT NULL,
   RISK_UNIT_SEQ      SMALLINT       NOT NULL,
   RISK_UNIT_TYPE     CHAR(4)        NOT NULL,
   DESCRIPTION        VARCHAR(60)    NOT NULL,
   VEHICLE_REG        CHAR(8)        NOT NULL WITH DEFAULT ' ',
   VEHICLE_MAKE       CHAR(15)       NOT NULL WITH DEFAULT ' ',
   VEHICLE_MODEL      CHAR(15)       NOT NULL WITH DEFAULT ' ',
   PROPERTY_POSTCODE  CHAR(8)        NOT NULL WITH DEFAULT ' ',
   INSURED_VALUE      DECIMAL(13,2)  NOT NULL WITH DEFAULT 0,
   PRIMARY KEY (CLAIM_ID, RISK_UNIT_SEQ),
   FOREIGN KEY (CLAIM_ID) REFERENCES CLMDB.CLM_CLAIM ON DELETE CASCADE)
  IN CLMDB.CLMTS02;

-- DCLGEN CLMDCON PREFIX CON
CREATE TABLE CLMDB.CLM_CONTACT
  (CONTACT_ID         INTEGER        NOT NULL,
   CONTACT_TYPE       CHAR(4)        NOT NULL,
   FIRST_NAME         VARCHAR(30),
   LAST_NAME          VARCHAR(40),
   COMPANY_NAME       VARCHAR(60),
   DATE_OF_BIRTH      DATE,
   ADDRESS_LINE1      VARCHAR(60),
   CITY               VARCHAR(40),
   POSTCODE           CHAR(8),
   PHONE_NUMBER       CHAR(20),
   EMAIL_ADDRESS      VARCHAR(100),
   TAX_ID_TOKEN       CHAR(32)       NOT NULL WITH DEFAULT ' ',
   GENAPP_CUST_NUM    INTEGER        NOT NULL WITH DEFAULT 0,
   VENDOR_TYPE        CHAR(8)        NOT NULL WITH DEFAULT ' ',
   PREFERRED_FLAG     CHAR(1)        NOT NULL WITH DEFAULT 'N',
   VENDOR_RATING      SMALLINT       NOT NULL WITH DEFAULT 0,
   SANCTION_STATUS    CHAR(4)        NOT NULL WITH DEFAULT 'UNCK',
   CREATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   UPDATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   PRIMARY KEY (CONTACT_ID))
  IN CLMDB.CLMTS02;
CREATE INDEX CLMDB.XCON01 ON CLMDB.CLM_CONTACT (LAST_NAME, POSTCODE);

-- DCLGEN CLMDCCR PREFIX CCR
CREATE TABLE CLMDB.CLM_CLAIM_CONTACT
  (CLAIM_ID           INTEGER        NOT NULL,
   CONTACT_ID         INTEGER        NOT NULL,
   CONTACT_ROLE       CHAR(8)        NOT NULL,
   EXPOSURE_ID        INTEGER        NOT NULL WITH DEFAULT 0,
   ADDED_TS           TIMESTAMP      NOT NULL WITH DEFAULT,
   PRIMARY KEY (CLAIM_ID, CONTACT_ID, CONTACT_ROLE),
   FOREIGN KEY (CLAIM_ID) REFERENCES CLMDB.CLM_CLAIM ON DELETE CASCADE)
  IN CLMDB.CLMTS02;
