SET CURRENT SQLID = 'CLMADM';

-- DCLGEN CLMDRSL PREFIX RSL
CREATE TABLE CLMDB.CLM_RESERVE_LINE
  (RL_ID              INTEGER        NOT NULL,
   CLAIM_ID           INTEGER        NOT NULL,
   EXPOSURE_ID        INTEGER        NOT NULL,
   COST_TYPE          CHAR(4)        NOT NULL,
   COST_CATEGORY      CHAR(8)        NOT NULL,
   OPEN_RESERVE       DECIMAL(13,2)  NOT NULL WITH DEFAULT 0,
   PENDING_APPROVAL   DECIMAL(13,2)  NOT NULL WITH DEFAULT 0,
   TOTAL_PAID         DECIMAL(13,2)  NOT NULL WITH DEFAULT 0,
   RECOVERY_RESERVE   DECIMAL(13,2)  NOT NULL WITH DEFAULT 0,
   TOTAL_RECOVERED    DECIMAL(13,2)  NOT NULL WITH DEFAULT 0,
   UPDATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   PRIMARY KEY (RL_ID),
   FOREIGN KEY (CLAIM_ID) REFERENCES CLMDB.CLM_CLAIM ON DELETE CASCADE)
  IN CLMDB.CLMTS04;
CREATE UNIQUE INDEX CLMDB.XRSL01
  ON CLMDB.CLM_RESERVE_LINE (EXPOSURE_ID, COST_TYPE, COST_CATEGORY);

-- DCLGEN CLMDTXN PREFIX TXN
CREATE TABLE CLMDB.CLM_TRANSACTION
  (TXN_ID             INTEGER        NOT NULL,
   CLAIM_ID           INTEGER        NOT NULL,
   EXPOSURE_ID        INTEGER        NOT NULL,
   RL_ID              INTEGER        NOT NULL,
   TXN_TYPE           CHAR(4)        NOT NULL,
   TXN_STATUS         CHAR(4)        NOT NULL,
   TXN_AMOUNT         DECIMAL(13,2)  NOT NULL,
   ERODES_RESERVE     CHAR(1)        NOT NULL WITH DEFAULT 'Y',
   PAYMENT_TYPE       CHAR(4)        NOT NULL WITH DEFAULT ' ',
   RECOVERY_CATEGORY  CHAR(8)        NOT NULL WITH DEFAULT ' ',
   CHECK_ID           INTEGER        NOT NULL WITH DEFAULT 0,
   CREATE_USER        CHAR(8)        NOT NULL,
   APPROVER_USER      CHAR(8)        NOT NULL WITH DEFAULT ' ',
   REJECT_REASON      CHAR(8)        NOT NULL WITH DEFAULT ' ',
   RELATED_TXN_ID     INTEGER        NOT NULL WITH DEFAULT 0,
   BUSINESS_DATE      DATE           NOT NULL,
   CREATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   APPROVED_TS        TIMESTAMP,
   PRIMARY KEY (TXN_ID),
   FOREIGN KEY (CLAIM_ID) REFERENCES CLMDB.CLM_CLAIM ON DELETE CASCADE)
  IN CLMDB.CLMTS04;
CREATE INDEX CLMDB.XTXN01 ON CLMDB.CLM_TRANSACTION (CLAIM_ID, TXN_TYPE);
CREATE INDEX CLMDB.XTXN02 ON CLMDB.CLM_TRANSACTION (TXN_STATUS, BUSINESS_DATE);

-- DCLGEN CLMDCHK PREFIX CHK
CREATE TABLE CLMDB.CLM_CHECK
  (CHECK_ID           INTEGER        NOT NULL,
   CLAIM_ID           INTEGER        NOT NULL,
   CHECK_NUMBER       CHAR(10)       NOT NULL WITH DEFAULT ' ',
   PAYEE_CONTACT_ID   INTEGER        NOT NULL,
   PAYEE_NAME         VARCHAR(60)    NOT NULL,
   PAYEE_ADDR1        VARCHAR(60),
   PAYEE_POSTCODE     CHAR(8),
   CHECK_AMOUNT       DECIMAL(13,2)  NOT NULL,
   PAY_METHOD         CHAR(4)        NOT NULL WITH DEFAULT 'CHEQ',
   SCHEDULED_DATE     DATE           NOT NULL,
   ISSUE_DATE         DATE,
   CHECK_STATUS       CHAR(4)        NOT NULL WITH DEFAULT 'PEND',
   BILLING_DISB_REF   CHAR(20)       NOT NULL WITH DEFAULT ' ',
   VOID_REASON        CHAR(8)        NOT NULL WITH DEFAULT ' ',
   CREATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   UPDATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   PRIMARY KEY (CHECK_ID),
   FOREIGN KEY (CLAIM_ID) REFERENCES CLMDB.CLM_CLAIM ON DELETE CASCADE)
  IN CLMDB.CLMTS04;
CREATE INDEX CLMDB.XCHK01 ON CLMDB.CLM_CHECK (CHECK_STATUS, SCHEDULED_DATE);
