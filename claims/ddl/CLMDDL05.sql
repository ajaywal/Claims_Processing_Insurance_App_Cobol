SET CURRENT SQLID = 'CLMADM';

-- DCLGEN CLMDSUB PREFIX SUB
CREATE TABLE CLMDB.CLM_SUBROGATION
  (CLAIM_ID           INTEGER        NOT NULL,
   SUBRO_STATUS       CHAR(4)        NOT NULL,
   ADVERSE_PARTY_ID   INTEGER        NOT NULL WITH DEFAULT 0,
   ADVERSE_CARRIER    VARCHAR(60),
   LIABILITY_PCT      DECIMAL(5,2)   NOT NULL WITH DEFAULT 0,
   EST_RECOVERY       DECIMAL(13,2)  NOT NULL WITH DEFAULT 0,
   OPENED_DATE        DATE           NOT NULL,
   CLOSED_DATE        DATE,
   CLOSE_OUTCOME      CHAR(8)        NOT NULL WITH DEFAULT ' ',
   PRIMARY KEY (CLAIM_ID),
   FOREIGN KEY (CLAIM_ID) REFERENCES CLMDB.CLM_CLAIM ON DELETE CASCADE)
  IN CLMDB.CLMTS05;

-- DCLGEN CLMDSAL PREFIX SAL
CREATE TABLE CLMDB.CLM_SALVAGE
  (CLAIM_ID           INTEGER        NOT NULL,
   INCIDENT_ID        INTEGER        NOT NULL,
   VENDOR_CONTACT_ID  INTEGER        NOT NULL WITH DEFAULT 0,
   SALVAGE_STATUS     CHAR(4)        NOT NULL,
   ASSIGNED_DATE      DATE           NOT NULL,
   EST_VALUE          DECIMAL(13,2)  NOT NULL WITH DEFAULT 0,
   SALE_DATE          DATE,
   SALE_AMOUNT        DECIMAL(13,2)  NOT NULL WITH DEFAULT 0,
   PRIMARY KEY (CLAIM_ID, INCIDENT_ID),
   FOREIGN KEY (CLAIM_ID) REFERENCES CLMDB.CLM_CLAIM ON DELETE CASCADE)
  IN CLMDB.CLMTS05;

-- DCLGEN CLMDLIT PREFIX LIT
CREATE TABLE CLMDB.CLM_LITIGATION
  (MATTER_ID          INTEGER        NOT NULL,
   CLAIM_ID           INTEGER        NOT NULL,
   MATTER_TYPE        CHAR(8)        NOT NULL,
   COURT_NAME         VARCHAR(60),
   CASE_NUMBER        CHAR(20)       NOT NULL WITH DEFAULT ' ',
   PLAINTIFF_ATTY_ID  INTEGER        NOT NULL WITH DEFAULT 0,
   DEFENSE_ATTY_ID    INTEGER        NOT NULL WITH DEFAULT 0,
   FILE_DATE          DATE           NOT NULL,
   TRIAL_DATE         DATE,
   MATTER_STATUS      CHAR(4)        NOT NULL WITH DEFAULT 'OPEN',
   RESOLUTION         CHAR(8)        NOT NULL WITH DEFAULT ' ',
   SETTLEMENT_AMOUNT  DECIMAL(13,2)  NOT NULL WITH DEFAULT 0,
   LEGAL_SPEND        DECIMAL(13,2)  NOT NULL WITH DEFAULT 0,
   CLOSED_DATE        DATE,
   PRIMARY KEY (MATTER_ID),
   FOREIGN KEY (CLAIM_ID) REFERENCES CLMDB.CLM_CLAIM ON DELETE CASCADE)
  IN CLMDB.CLMTS05;

-- DCLGEN CLMDSSC PREFIX SSC
CREATE TABLE CLMDB.CLM_SIU_SCORE
  (CLAIM_ID           INTEGER        NOT NULL,
   RULE_CODE          CHAR(8)        NOT NULL,
   POINTS             SMALLINT       NOT NULL,
   EVIDENCE_TEXT      VARCHAR(80),
   EVAL_TS            TIMESTAMP      NOT NULL WITH DEFAULT,
   PRIMARY KEY (CLAIM_ID, RULE_CODE),
   FOREIGN KEY (CLAIM_ID) REFERENCES CLMDB.CLM_CLAIM ON DELETE CASCADE)
  IN CLMDB.CLMTS05;

-- DCLGEN CLMDRIC PREFIX RIC
CREATE TABLE CLMDB.CLM_RI_CESSION
  (CLAIM_ID           INTEGER        NOT NULL,
   TREATY_CODE        CHAR(8)        NOT NULL,
   GROSS_INCURRED     DECIMAL(13,2)  NOT NULL,
   RETAINED_AMOUNT    DECIMAL(13,2)  NOT NULL,
   CEDED_AMOUNT       DECIMAL(13,2)  NOT NULL,
   NOTIFIED_FLAG      CHAR(1)        NOT NULL WITH DEFAULT 'N',
   CALC_DATE          DATE           NOT NULL,
   PRIMARY KEY (CLAIM_ID, TREATY_CODE),
   FOREIGN KEY (CLAIM_ID) REFERENCES CLMDB.CLM_CLAIM ON DELETE CASCADE)
  IN CLMDB.CLMTS05;
