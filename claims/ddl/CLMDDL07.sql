SET CURRENT SQLID = 'CLMADM';

-- DCLGEN CLMDAUC PREFIX AUC
CREATE TABLE CLMDB.CLM_AUDIT_CHAIN
  (CHAIN_SEQ          INTEGER        NOT NULL,
   CLAIM_ID           INTEGER        NOT NULL,
   EVENT_CODE         CHAR(8)        NOT NULL,
   PAYLOAD_DIGEST     CHAR(16)       NOT NULL,
   PREV_HASH          CHAR(16)       NOT NULL,
   CHAIN_HASH         CHAR(16)       NOT NULL,
   USER_ID            CHAR(8)        NOT NULL,
   PROGRAM_ID         CHAR(8)        NOT NULL,
   EVENT_TS           TIMESTAMP      NOT NULL WITH DEFAULT,
   SEALED_FLAG        CHAR(1)        NOT NULL WITH DEFAULT 'N',
   PRIMARY KEY (CHAIN_SEQ))
  IN CLMDB.CLMTS07;

-- DCLGEN CLMDEVQ PREFIX EVQ
CREATE TABLE CLMDB.CLM_EVENT_QUEUE
  (EVENT_ID           INTEGER        NOT NULL,
   EVENT_TYPE         CHAR(8)        NOT NULL,
   DIRECTION          CHAR(1)        NOT NULL,
   SOURCE_SYSTEM      CHAR(4)        NOT NULL,
   TARGET_SYSTEM      CHAR(4)        NOT NULL,
   EVENT_KEY          CHAR(20)       NOT NULL,
   PAYLOAD            VARCHAR(1000)  NOT NULL,
   EVENT_STATUS       CHAR(4)        NOT NULL WITH DEFAULT 'NEW',
   RETRY_COUNT        SMALLINT       NOT NULL WITH DEFAULT 0,
   ERROR_TEXT         VARCHAR(80),
   CREATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   PROCESSED_TS       TIMESTAMP,
   PRIMARY KEY (EVENT_ID))
  IN CLMDB.CLMTS07;
CREATE INDEX CLMDB.XEVQ01 ON CLMDB.CLM_EVENT_QUEUE (EVENT_STATUS, DIRECTION, CREATE_TS);

-- DCLGEN CLMDFNI PREFIX FNI
CREATE TABLE CLMDB.CLM_FNOL_INTAKE
  (INTAKE_ID          INTEGER        NOT NULL,
   INTAKE_SOURCE      CHAR(4)        NOT NULL,
   RAW_RECORD         VARCHAR(600)   NOT NULL,
   INTAKE_STATUS      CHAR(4)        NOT NULL WITH DEFAULT 'NEW',
   CLAIM_ID           INTEGER        NOT NULL WITH DEFAULT 0,
   ERROR_CODE         CHAR(8)        NOT NULL WITH DEFAULT ' ',
   ERROR_TEXT         VARCHAR(80),
   RECEIVED_TS        TIMESTAMP      NOT NULL WITH DEFAULT,
   PROCESSED_TS       TIMESTAMP,
   PRIMARY KEY (INTAKE_ID))
  IN CLMDB.CLMTS07;

-- DCLGEN CLMDISO PREFIX ISO
CREATE TABLE CLMDB.CLM_ISO_REQUEST
  (ISO_REQ_ID         INTEGER        NOT NULL,
   CLAIM_ID           INTEGER        NOT NULL,
   REQUEST_TYPE       CHAR(4)        NOT NULL,
   ISO_STATUS         CHAR(4)        NOT NULL WITH DEFAULT 'PEND',
   MATCH_COUNT        SMALLINT       NOT NULL WITH DEFAULT 0,
   ISO_REF            CHAR(16)       NOT NULL WITH DEFAULT ' ',
   SENT_TS            TIMESTAMP,
   RESPONSE_TS        TIMESTAMP,
   PRIMARY KEY (ISO_REQ_ID))
  IN CLMDB.CLMTS07;

-- DCLGEN CLMDERR PREFIX ERR
CREATE TABLE CLMDB.CLM_ERROR_LOG
  (ERROR_ID           INTEGER        NOT NULL,
   PROGRAM_ID         CHAR(8)        NOT NULL,
   PARAGRAPH_NAME     CHAR(30)       NOT NULL,
   SQLCODE_VALUE      INTEGER        NOT NULL WITH DEFAULT 0,
   CICS_RESP          INTEGER        NOT NULL WITH DEFAULT 0,
   ERROR_TEXT         VARCHAR(120)   NOT NULL,
   ENTITY_KEY         CHAR(20)       NOT NULL WITH DEFAULT ' ',
   USER_ID            CHAR(8)        NOT NULL,
   TRAN_ID            CHAR(4)        NOT NULL WITH DEFAULT ' ',
   ERROR_TS           TIMESTAMP      NOT NULL WITH DEFAULT,
   PRIMARY KEY (ERROR_ID))
  IN CLMDB.CLMTS07;
