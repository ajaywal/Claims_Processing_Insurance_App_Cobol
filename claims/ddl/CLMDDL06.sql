SET CURRENT SQLID = 'CLMADM';

-- DCLGEN CLMDACT PREFIX ACT
CREATE TABLE CLMDB.CLM_ACTIVITY
  (ACTIVITY_ID        INTEGER        NOT NULL,
   CLAIM_ID           INTEGER        NOT NULL,
   EXPOSURE_ID        INTEGER        NOT NULL WITH DEFAULT 0,
   PATTERN_CODE       CHAR(8)        NOT NULL,
   SUBJECT            VARCHAR(60)    NOT NULL,
   PRIORITY           CHAR(1)        NOT NULL WITH DEFAULT '3',
   ACTIVITY_STATUS    CHAR(4)        NOT NULL WITH DEFAULT 'OPEN',
   ASSIGNED_USER      CHAR(8)        NOT NULL,
   DUE_DATE           DATE           NOT NULL,
   ESCALATION_DATE    DATE           NOT NULL,
   ESCALATED_FLAG     CHAR(1)        NOT NULL WITH DEFAULT 'N',
   APPROVAL_TXN_ID    INTEGER        NOT NULL WITH DEFAULT 0,
   CREATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   COMPLETE_TS        TIMESTAMP,
   COMPLETE_USER      CHAR(8)        NOT NULL WITH DEFAULT ' ',
   PRIMARY KEY (ACTIVITY_ID),
   FOREIGN KEY (CLAIM_ID) REFERENCES CLMDB.CLM_CLAIM ON DELETE CASCADE)
  IN CLMDB.CLMTS06;
CREATE INDEX CLMDB.XACT01 ON CLMDB.CLM_ACTIVITY (ASSIGNED_USER, ACTIVITY_STATUS, DUE_DATE);
CREATE INDEX CLMDB.XACT02 ON CLMDB.CLM_ACTIVITY (ACTIVITY_STATUS, ESCALATION_DATE);

-- DCLGEN CLMDNOT PREFIX NTE
CREATE TABLE CLMDB.CLM_NOTE
  (NOTE_ID            INTEGER        NOT NULL,
   CLAIM_ID           INTEGER        NOT NULL,
   EXPOSURE_ID        INTEGER        NOT NULL WITH DEFAULT 0,
   NOTE_TOPIC         CHAR(8)        NOT NULL,
   SUBJECT            VARCHAR(60)    NOT NULL,
   BODY_TEXT          VARCHAR(2000)  NOT NULL,
   CONFIDENTIAL_FLAG  CHAR(1)        NOT NULL WITH DEFAULT 'N',
   AUTHOR_USER        CHAR(8)        NOT NULL,
   CREATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   PRIMARY KEY (NOTE_ID),
   FOREIGN KEY (CLAIM_ID) REFERENCES CLMDB.CLM_CLAIM ON DELETE CASCADE)
  IN CLMDB.CLMTS06;

-- DCLGEN CLMDDOC PREFIX DOC
CREATE TABLE CLMDB.CLM_DOCUMENT
  (DOC_ID             INTEGER        NOT NULL,
   CLAIM_ID           INTEGER        NOT NULL,
   DOC_TYPE           CHAR(8)        NOT NULL,
   DOC_NAME           VARCHAR(60)    NOT NULL,
   DOC_STATUS         CHAR(4)        NOT NULL WITH DEFAULT 'RQST',
   RECIPIENT_ID       INTEGER        NOT NULL WITH DEFAULT 0,
   DMS_REF            CHAR(32)       NOT NULL WITH DEFAULT ' ',
   REQUEST_DATE       DATE           NOT NULL,
   RECEIVED_DATE      DATE,
   CREATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   PRIMARY KEY (DOC_ID),
   FOREIGN KEY (CLAIM_ID) REFERENCES CLMDB.CLM_CLAIM ON DELETE CASCADE)
  IN CLMDB.CLMTS06;

-- DCLGEN CLMDSRQ PREFIX SRQ
CREATE TABLE CLMDB.CLM_SERVICE_REQUEST
  (SR_ID              INTEGER        NOT NULL,
   CLAIM_ID           INTEGER        NOT NULL,
   EXPOSURE_ID        INTEGER        NOT NULL WITH DEFAULT 0,
   VENDOR_CONTACT_ID  INTEGER        NOT NULL,
   SERVICE_TYPE       CHAR(8)        NOT NULL,
   SR_STATUS          CHAR(4)        NOT NULL WITH DEFAULT 'RQST',
   REQUEST_DATE       DATE           NOT NULL,
   QUOTE_AMOUNT       DECIMAL(13,2)  NOT NULL WITH DEFAULT 0,
   INVOICE_AMOUNT     DECIMAL(13,2)  NOT NULL WITH DEFAULT 0,
   COMPLETED_DATE     DATE,
   PAYMENT_TXN_ID     INTEGER        NOT NULL WITH DEFAULT 0,
   UPDATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   PRIMARY KEY (SR_ID),
   FOREIGN KEY (CLAIM_ID) REFERENCES CLMDB.CLM_CLAIM ON DELETE CASCADE)
  IN CLMDB.CLMTS06;

-- DCLGEN CLMDHIS PREFIX HIS
CREATE TABLE CLMDB.CLM_HISTORY
  (HISTORY_ID         INTEGER        NOT NULL,
   CLAIM_ID           INTEGER        NOT NULL,
   EVENT_TYPE         CHAR(8)        NOT NULL,
   DESCRIPTION        VARCHAR(120)   NOT NULL,
   USER_ID            CHAR(8)        NOT NULL,
   PROGRAM_ID         CHAR(8)        NOT NULL,
   EVENT_TS           TIMESTAMP      NOT NULL WITH DEFAULT,
   PRIMARY KEY (HISTORY_ID))
  IN CLMDB.CLMTS06;
CREATE INDEX CLMDB.XHIS01 ON CLMDB.CLM_HISTORY (CLAIM_ID, EVENT_TS);
