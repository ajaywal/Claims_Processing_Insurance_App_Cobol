SET CURRENT SQLID = 'CLMADM';

-- DCLGEN CLMDCTL PREFIX CTL
CREATE TABLE CLMDB.CLM_CONTROL
  (CONTROL_KEY        CHAR(8)        NOT NULL,
   BUSINESS_DATE      DATE           NOT NULL,
   PRIOR_BUS_DATE     DATE           NOT NULL,
   BATCH_STATUS       CHAR(1)        NOT NULL WITH DEFAULT 'O',
   LAST_EOD_TS        TIMESTAMP,
   CURRENCY_CODE      CHAR(3)        NOT NULL WITH DEFAULT 'GBP',
   UPDATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   PRIMARY KEY (CONTROL_KEY))
  IN CLMDB.CLMTS01;

-- DCLGEN CLMDSEQ PREFIX SEQ
CREATE TABLE CLMDB.CLM_SEQUENCE
  (SEQ_NAME           CHAR(8)        NOT NULL,
   NEXT_VALUE         INTEGER        NOT NULL,
   INCREMENT_BY       SMALLINT       NOT NULL WITH DEFAULT 1,
   MAX_VALUE          INTEGER        NOT NULL,
   CYCLE_FLAG         CHAR(1)        NOT NULL WITH DEFAULT 'N',
   PREFIX_TEXT        CHAR(4)        NOT NULL WITH DEFAULT ' ',
   UPDATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   PRIMARY KEY (SEQ_NAME))
  IN CLMDB.CLMTS01;

-- DCLGEN CLMDCOD PREFIX COD
CREATE TABLE CLMDB.CLM_CODE_TABLE
  (TABLE_NAME         CHAR(8)        NOT NULL,
   CODE_VALUE         CHAR(10)       NOT NULL,
   DESCRIPTION        VARCHAR(60)    NOT NULL,
   PARENT_CODE        CHAR(10)       NOT NULL WITH DEFAULT ' ',
   SORT_ORDER         SMALLINT       NOT NULL WITH DEFAULT 0,
   ACTIVE_FLAG        CHAR(1)        NOT NULL WITH DEFAULT 'Y',
   PRIMARY KEY (TABLE_NAME, CODE_VALUE))
  IN CLMDB.CLMTS01;

-- DCLGEN CLMDGRP PREFIX GRP
CREATE TABLE CLMDB.CLM_GROUP
  (GROUP_CODE         CHAR(8)        NOT NULL,
   GROUP_NAME         VARCHAR(40)    NOT NULL,
   PARENT_GROUP       CHAR(8)        NOT NULL WITH DEFAULT ' ',
   GROUP_TYPE         CHAR(4)        NOT NULL,
   SUPERVISOR_ID      CHAR(8)        NOT NULL,
   REGION_CODE        CHAR(4)        NOT NULL,
   ACTIVE_FLAG        CHAR(1)        NOT NULL WITH DEFAULT 'Y',
   PRIMARY KEY (GROUP_CODE))
  IN CLMDB.CLMTS01;

-- DCLGEN CLMDUSR PREFIX USR
CREATE TABLE CLMDB.CLM_USER
  (USER_ID            CHAR(8)        NOT NULL,
   USER_NAME          VARCHAR(40)    NOT NULL,
   GROUP_CODE         CHAR(8)        NOT NULL,
   AUTH_PROFILE       CHAR(8)        NOT NULL,
   SUPERVISOR_ID      CHAR(8)        NOT NULL WITH DEFAULT ' ',
   LOB_SKILLS         CHAR(8)        NOT NULL WITH DEFAULT 'MHC',
   OPEN_CLAIMS        SMALLINT       NOT NULL WITH DEFAULT 0,
   MAX_CLAIMS         SMALLINT       NOT NULL WITH DEFAULT 150,
   LAST_ASSIGN_TS     TIMESTAMP,
   ACTIVE_FLAG        CHAR(1)        NOT NULL WITH DEFAULT 'Y',
   PRIMARY KEY (USER_ID))
  IN CLMDB.CLMTS01;

-- DCLGEN CLMDAUL PREFIX AUL
CREATE TABLE CLMDB.CLM_AUTHORITY_LIMIT
  (AUTH_PROFILE       CHAR(8)        NOT NULL,
   LIMIT_TYPE         CHAR(8)        NOT NULL,
   COVERAGE_TYPE      CHAR(8)        NOT NULL,
   LIMIT_AMOUNT       DECIMAL(13,2)  NOT NULL,
   PRIMARY KEY (AUTH_PROFILE, LIMIT_TYPE, COVERAGE_TYPE))
  IN CLMDB.CLMTS01;

-- DCLGEN CLMDASR PREFIX ASR
CREATE TABLE CLMDB.CLM_ASSIGN_RULE
  (RULE_SEQ           SMALLINT       NOT NULL,
   LOSS_TYPE          CHAR(4)        NOT NULL,
   SEGMENT_CODE       CHAR(8)        NOT NULL,
   MIN_SEVERITY       SMALLINT       NOT NULL WITH DEFAULT 0,
   REGION_CODE        CHAR(4)        NOT NULL WITH DEFAULT '*',
   GROUP_CODE         CHAR(8)        NOT NULL,
   STRATEGY           CHAR(4)        NOT NULL,
   ACTIVE_FLAG        CHAR(1)        NOT NULL WITH DEFAULT 'Y',
   PRIMARY KEY (RULE_SEQ))
  IN CLMDB.CLMTS01;

-- DCLGEN CLMDAPT PREFIX APT
CREATE TABLE CLMDB.CLM_ACTIVITY_PATTERN
  (PATTERN_CODE       CHAR(8)        NOT NULL,
   SUBJECT            VARCHAR(60)    NOT NULL,
   CATEGORY           CHAR(8)        NOT NULL,
   TRIGGER_EVENT      CHAR(8)        NOT NULL WITH DEFAULT ' ',
   LOSS_TYPE          CHAR(4)        NOT NULL WITH DEFAULT '*',
   TARGET_DAYS        SMALLINT       NOT NULL,
   ESCALATION_DAYS    SMALLINT       NOT NULL,
   PRIORITY           CHAR(1)        NOT NULL WITH DEFAULT '3',
   MANDATORY_FLAG     CHAR(1)        NOT NULL WITH DEFAULT 'N',
   PRIMARY KEY (PATTERN_CODE))
  IN CLMDB.CLMTS01;

-- DCLGEN CLMDSRL PREFIX SRL
CREATE TABLE CLMDB.CLM_SIU_RULE
  (RULE_CODE          CHAR(8)        NOT NULL,
   DESCRIPTION        VARCHAR(60)    NOT NULL,
   POINTS             SMALLINT       NOT NULL,
   ACTIVE_FLAG        CHAR(1)        NOT NULL WITH DEFAULT 'Y',
   PRIMARY KEY (RULE_CODE))
  IN CLMDB.CLMTS01;

-- DCLGEN CLMDCAT PREFIX CAT
CREATE TABLE CLMDB.CLM_CATASTROPHE
  (CAT_CODE           CHAR(8)        NOT NULL,
   CAT_NAME           VARCHAR(40)    NOT NULL,
   CAT_TYPE           CHAR(8)        NOT NULL,
   START_DATE         DATE           NOT NULL,
   END_DATE           DATE           NOT NULL,
   POSTCODE_AREA      CHAR(4)        NOT NULL,
   ACTIVE_FLAG        CHAR(1)        NOT NULL WITH DEFAULT 'Y',
   PRIMARY KEY (CAT_CODE))
  IN CLMDB.CLMTS01;

-- DCLGEN CLMDRIT PREFIX RIT
CREATE TABLE CLMDB.CLM_RI_TREATY
  (TREATY_CODE        CHAR(8)        NOT NULL,
   TREATY_TYPE        CHAR(4)        NOT NULL,
   POLICY_TYPE        CHAR(1)        NOT NULL,
   RETENTION_AMOUNT   DECIMAL(13,2)  NOT NULL,
   LIMIT_AMOUNT       DECIMAL(13,2)  NOT NULL,
   CEDED_PCT          DECIMAL(5,2)   NOT NULL,
   EFF_DATE           DATE           NOT NULL,
   EXP_DATE           DATE           NOT NULL,
   PRIMARY KEY (TREATY_CODE))
  IN CLMDB.CLMTS01;
