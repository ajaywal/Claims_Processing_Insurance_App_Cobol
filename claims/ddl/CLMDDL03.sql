SET CURRENT SQLID = 'CLMADM';

-- DCLGEN CLMDINC PREFIX INC
CREATE TABLE CLMDB.CLM_INCIDENT
  (INCIDENT_ID        INTEGER        NOT NULL,
   CLAIM_ID           INTEGER        NOT NULL,
   INCIDENT_TYPE      CHAR(4)        NOT NULL,
   RISK_UNIT_SEQ      SMALLINT       NOT NULL WITH DEFAULT 0,
   DESCRIPTION        VARCHAR(200)   NOT NULL,
   SEVERITY           SMALLINT       NOT NULL WITH DEFAULT 1,
   VEHICLE_REG        CHAR(8)        NOT NULL WITH DEFAULT ' ',
   DRIVEABLE_FLAG     CHAR(1)        NOT NULL WITH DEFAULT 'Y',
   ESTIMATED_DAMAGE   DECIMAL(13,2)  NOT NULL WITH DEFAULT 0,
   TOTAL_LOSS_FLAG    CHAR(1)        NOT NULL WITH DEFAULT 'N',
   INJURY_TYPE        CHAR(8)        NOT NULL WITH DEFAULT ' ',
   INJURED_CONTACT_ID INTEGER        NOT NULL WITH DEFAULT 0,
   CREATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   PRIMARY KEY (INCIDENT_ID),
   FOREIGN KEY (CLAIM_ID) REFERENCES CLMDB.CLM_CLAIM ON DELETE CASCADE)
  IN CLMDB.CLMTS03;
CREATE INDEX CLMDB.XINC01 ON CLMDB.CLM_INCIDENT (CLAIM_ID);

-- DCLGEN CLMDEXP PREFIX EXP
CREATE TABLE CLMDB.CLM_EXPOSURE
  (EXPOSURE_ID        INTEGER        NOT NULL,
   CLAIM_ID           INTEGER        NOT NULL,
   EXPOSURE_SEQ       SMALLINT       NOT NULL,
   EXPOSURE_TYPE      CHAR(8)        NOT NULL,
   COVERAGE_TYPE      CHAR(8)        NOT NULL,
   COV_SEQ            SMALLINT       NOT NULL,
   CLAIMANT_ID        INTEGER        NOT NULL,
   INCIDENT_ID        INTEGER        NOT NULL WITH DEFAULT 0,
   EXPOSURE_STATE     CHAR(4)        NOT NULL WITH DEFAULT 'DRFT',
   VALIDATION_LEVEL   CHAR(4)        NOT NULL WITH DEFAULT 'NEWL',
   SEGMENT_CODE       CHAR(8)        NOT NULL WITH DEFAULT ' ',
   ASSIGNED_USER      CHAR(8)        NOT NULL WITH DEFAULT ' ',
   OPEN_RESERVE       DECIMAL(13,2)  NOT NULL WITH DEFAULT 0,
   TOTAL_PAID         DECIMAL(13,2)  NOT NULL WITH DEFAULT 0,
   TOTAL_RECOVERED    DECIMAL(13,2)  NOT NULL WITH DEFAULT 0,
   DEDUCTIBLE_APPLIED DECIMAL(13,2)  NOT NULL WITH DEFAULT 0,
   CREATE_DATE        DATE           NOT NULL,
   CLOSE_DATE         DATE,
   CLOSE_REASON       CHAR(8)        NOT NULL WITH DEFAULT ' ',
   UPDATE_TS          TIMESTAMP      NOT NULL WITH DEFAULT,
   VERSION_NO         INTEGER        NOT NULL WITH DEFAULT 1,
   PRIMARY KEY (EXPOSURE_ID),
   FOREIGN KEY (CLAIM_ID) REFERENCES CLMDB.CLM_CLAIM ON DELETE CASCADE)
  IN CLMDB.CLMTS03;
CREATE UNIQUE INDEX CLMDB.XEXP01 ON CLMDB.CLM_EXPOSURE (CLAIM_ID, EXPOSURE_SEQ);
